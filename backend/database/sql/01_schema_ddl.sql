CREATE TYPE action_type AS ENUM ('ESCROW_HOLD', 'ESCROW_RELEASE', 'ESCROW_REFUND');
CREATE TYPE status AS ENUM ('FUNDED', 'IN_PROGRESS', 'COMPLETED');

CREATE TABLE clients (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name varchar NOT NULL,
  escrow_balance decimal(10,2) NOT NULL CHECK (escrow_balance >= 0.00),
  created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- ESCROW_HOLD: funds reserved for a contract. ESCROW_RELEASE: funds added back or credited.
-- ESCROW_REFUND is reserved for a future cancellation flow and is not written by the current workflows.
CREATE TABLE wallet_audit_logs (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  client_id integer NOT NULL REFERENCES clients (id) ON DELETE RESTRICT,
  amount_changed decimal(10,2) NOT NULL,
  action_type action_type NOT NULL,
  balance_after decimal(10,2) NOT NULL,
  timestamp timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE freelancers (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name varchar NOT NULL,
  latitude decimal(10,4) NOT NULL,
  longitude decimal(10,4) NOT NULL,
  is_available boolean NOT NULL
);

CREATE TABLE contracts (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  client_id integer NOT NULL REFERENCES clients (id) ON DELETE RESTRICT,
  freelancer_id integer NOT NULL REFERENCES freelancers (id) ON DELETE RESTRICT,
  budget decimal(10,2) NOT NULL,
  status status NOT NULL DEFAULT 'FUNDED',
  created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT contracts_positive_budget CHECK (budget > 0)
);
